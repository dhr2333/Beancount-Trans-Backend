# --------------------------------------------------------------------------- #
# 管理命令 ensure_collect_bean
# --------------------------------------------------------------------------- #
class TestEnsureCollectBeanCommand:
    def test_creates_collect_bean_for_legacy_user(self, user):
        _reset_to_legacy(user)
        assert not _collect_path(user).exists()

        out = _run_command()

        assert _collect_path(user).is_file()
        assert _collect_text(user) == COLLECT_HEADER
        assert COLLECT_INCLUDE in _include_lines(user)
        assert f'用户 {user.username}: 新建 1 个, 已存在 0 个, 错误 0 个' in out
        assert '=== 补齐完成 ===' in out

    def test_repeated_run_is_idempotent(self, user):
        _reset_to_legacy(user)
        _run_command()
        content_after_first = _collect_text(user)
        main_after_first = _main_text(user)

        out_second = _run_command()

        assert _collect_text(user) == content_after_first
        assert _main_text(user) == main_after_first
        assert _include_lines(user).count(COLLECT_INCLUDE) == 1
        assert f'用户 {user.username}: 新建 0 个, 已存在 1 个, 错误 0 个' in out_second

    def test_user_filter_reports_totals(self, user, assets_dir):
        _reset_to_legacy(user)

        out = _run_command(user=user.username)

        assert _collect_path(user).is_file()
        assert '新建文件数: 1' in out
        assert '已存在文件数: 0' in out

    def test_dry_run_writes_nothing(self, user):
        _reset_to_legacy(user)
        main_before = _main_text(user)

        out = _run_command(dry_run=True)

        assert not _collect_path(user).exists()
        assert _main_text(user) == main_before
        assert COLLECT_INCLUDE not in _include_lines(user)
        assert '模拟运行模式' in out
        assert f'计划创建: {BeanFileManager.get_collect_bean_path(user)}' in out

    def test_user_filter_only_processes_target_user(self, user, assets_dir):
        other = User.objects.create_user(username='otheruser', password='testpass123')
        _reset_to_legacy(user)
        _reset_to_legacy(other)

        out = _run_command(user=user.username)

        assert _collect_path(user).is_file()
        assert COLLECT_INCLUDE in _include_lines(user)
        # 其他用户完全未被处理
        assert not _collect_path(other).exists()
        assert COLLECT_INCLUDE not in _include_lines(other)
        assert other.username not in out
