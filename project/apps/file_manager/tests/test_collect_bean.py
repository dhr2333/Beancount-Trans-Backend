class TestGetCollectBeanPath:
    def test_matches_assets_layout(self, user, assets_dir):
        expected = os.path.join(str(assets_dir), user.username, 'trans', 'collect.bean')

        assert BeanFileManager.get_collect_bean_path(user) == expected

    def test_accepts_username_string(self, assets_dir):
        expected = os.path.join(str(assets_dir), 'someone', 'trans', 'collect.bean')

        assert BeanFileManager.get_collect_bean_path('someone') == expected


# --------------------------------------------------------------------------- #
# ensure_collect_bean
# --------------------------------------------------------------------------- #
class TestEnsureCollectBean:
    def test_creates_file_with_header_and_single_include(self, user):
        _reset_to_legacy(user)
        assert not _collect_path(user).exists()
        assert COLLECT_INCLUDE not in _include_lines(user)

        BeanFileManager.ensure_collect_bean(user)

        assert _collect_path(user).is_file()
        assert _collect_text(user) == COLLECT_HEADER
        assert _include_lines(user).count(COLLECT_INCLUDE) == 1

    def test_is_idempotent(self, user):
        BeanFileManager.ensure_collect_bean(user)
        content_after_first = _collect_text(user)
        includes_after_first = list(_include_lines(user))

        BeanFileManager.ensure_collect_bean(user)

        assert _collect_text(user) == content_after_first
        assert _include_lines(user) == includes_after_first
        assert _include_lines(user).count(COLLECT_INCLUDE) == 1

    def test_does_not_overwrite_existing_content(self, user):
        custom = (
            '2025-01-20 * "自定义条目" "保留我"\n'
            '  Assets:Test                100.00 CNY\n'
            '  Expenses:Test             -100.00 CNY\n'
        )
        _collect_path(user).write_text(custom, encoding='utf-8')

        BeanFileManager.ensure_collect_bean(user)

        assert _collect_text(user) == custom
        assert '自定义条目' in _collect_text(user)


# --------------------------------------------------------------------------- #
# append_to_collect_bean
# --------------------------------------------------------------------------- #
class TestAppendToCollectBean:
    def test_first_write_creates_file_with_header_and_directives(self, user):
        _reset_to_legacy(user)
        d1 = '2025-01-01 * "a" "b"'
        d2 = '2025-01-02 * "c" "d"'

        BeanFileManager.append_to_collect_bean(user, [d1, d2])

        text = _collect_text(user)
        assert text.startswith(COLLECT_HEADER)
        assert text == COLLECT_HEADER + d1 + '\n\n' + d2 + '\n\n'
        assert COLLECT_INCLUDE in _include_lines(user)

    def test_second_write_appends_after_existing_content(self, user):
        BeanFileManager.append_to_collect_bean(user, ['first-1', 'first-2'])
        before = _collect_text(user)

        BeanFileManager.append_to_collect_bean(user, ['second-1'])

        after = _collect_text(user)
        # 原有内容是新内容的前缀，新指令追加在末尾
        assert after.startswith(before)
        assert after == before + 'second-1\n\n'

    @pytest.mark.parametrize('directives', [[], None])
    def test_empty_directives_write_nothing(self, user, directives):
        BeanFileManager.ensure_collect_bean(user)
        baseline = _collect_text(user)
        includes_before = list(_include_lines(user))

        BeanFileManager.append_to_collect_bean(user, directives)

        assert _collect_path(user).is_file()
        assert _collect_text(user) == baseline
        assert _include_lines(user) == includes_before

    def test_empty_directives_still_ensure_missing_file(self, user):
        _reset_to_legacy(user)
        assert not _collect_path(user).exists()

        BeanFileManager.append_to_collect_bean(user, [])

        assert _collect_path(user).is_file()
        assert _collect_text(user) == COLLECT_HEADER
        assert COLLECT_INCLUDE in _include_lines(user)


