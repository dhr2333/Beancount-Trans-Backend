"""collect.bean 系统账本功能测试

覆盖：
- BeanFileManager.get_collect_bean_path 路径拼接
- BeanFileManager.ensure_collect_bean 创建 / 幂等 / 不覆盖已有内容
- BeanFileManager.append_to_collect_bean 追加语义 / 空输入不写入
- BeanFileManager.init_user_bean_structure 在用户创建时接入 collect.bean
- 管理命令 ensure_collect_bean（首次补齐 / 幂等 / --dry-run / --user）

所有测试将 settings.ASSETS_BASE_PATH 指向 tmp_path，避免污染真实 Assets 目录。
"""
import io
import os
from pathlib import Path

import pytest
from django.conf import settings
from django.contrib.auth import get_user_model
from django.core.management import call_command

from project.utils.file import BeanFileManager

User = get_user_model()

pytestmark = pytest.mark.django_db

COLLECT_HEADER = (
    "; Trans directory - Auto-generated includes\n"
    "; This file is automatically generated by the platform\n\n"
)
COLLECT_INCLUDE = 'include "collect.bean"'


@pytest.fixture
def assets_dir(tmp_path, monkeypatch):
    """把 ASSETS_BASE_PATH 指向临时目录，隔离文件系统。"""
    base = tmp_path / 'Assets'
    base.mkdir()
    monkeypatch.setattr(settings, 'ASSETS_BASE_PATH', str(base))
    return base


@pytest.fixture
def user(assets_dir):
    return User.objects.create_user(username='collectuser', password='testpass123')


def _collect_path(user_or_username):
    return Path(BeanFileManager.get_collect_bean_path(user_or_username))


def _collect_text(user):
    return _collect_path(user).read_text(encoding='utf-8')


def _main_text(user):
    return Path(BeanFileManager.get_trans_main_bean_path(user)).read_text(encoding='utf-8')


def _include_lines(user):
    return [
        line.strip()
        for line in _main_text(user).splitlines()
        if line.strip().startswith('include ')
    ]


def _remove_include_line(user, include_line):
    """从 trans/main.bean 中删除指定 include 行（用于模拟存量用户）。"""
    path = Path(BeanFileManager.get_trans_main_bean_path(user))
    lines = [
        line
        for line in path.read_text(encoding='utf-8').splitlines(keepends=True)
        if line.strip() != include_line
    ]
    path.write_text(''.join(lines), encoding='utf-8')


def _reset_to_legacy(user):
    """删除 collect.bean 及其 include 行，模拟尚未补齐的存量用户。"""
    _collect_path(user).unlink()
    _remove_include_line(user, COLLECT_INCLUDE)


def _run_command(**kwargs):
    out = io.StringIO()
    call_command('ensure_collect_bean', stdout=out, **kwargs)
    return out.getvalue()


